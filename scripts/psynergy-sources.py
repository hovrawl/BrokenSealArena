#!/usr/bin/env python3
"""Where each Psynergy comes from, read from the decompilation's tables.

Usage: psynergy-sources.py GAME_DIR   (e.g. ~/alchemy/games/tbs)

Prints, for every ability a character can learn by some route: the English name, its
element, PP, where it can be used, and the sources: the classes that teach it (with
the lowest level), the items that grant it, and the arena's Psynergy shop. Abilities
that are none of those but are usable by a player (field Psynergy and the like) are
listed last: those are the ones the story teaches for good or never at all.
"""
import re
import sys
from collections import defaultdict

game = sys.argv[1].rstrip("/")


def read(path):
    return open(game + "/" + path, encoding="utf-8").read()


# ability names: MsgAbilityName is the first of 519 consecutive messages
po = read("text/en.po")
msgs = {int(i): t for i, t in re.findall(r'msgid "(\d+)"\nmsgstr "([^\n]*)"', po)}
first = int(re.search(r'msgctxt "MsgAbilityName"\nmsgid "(\d+)"', po).group(1))
by_number = {n: msgs.get(first + n, "?") for n in range(519)}

# the ability table: one block per row, in order
table = read("src/game/ability_table.c")
body = table[table.index("gAbilityDefinitions[] = {"):]
rows = re.findall(r"\n    // [^\n]*\n    \{(.*?)\n    \},?|\n    // [^\n]*\n    \{0\},?", body, re.S)
blocks = re.split(r"\n    // [^\n]*\n", body)[1:]
abilities = []
for b in blocks:
    flags = re.search(r"\.flags = ([^,\n]*)", b)
    f = flags.group(1) if flags else ""
    abilities.append({
        "battle": "USABLE_IN_BATTLE" in f,
        "field": "USABLE_IN_FIELD" in f or "fieldPsynergy" in b,
        "kind": (re.search(r"ABILITY_FORMULA_(\w+)", f) or [None, ""])[1],
        "element": (re.search(r"\.element = ELEMENT_(\w+)", b) or [None, "NONE"])[1],
        "pp": int((re.search(r"\.ppCost = (\d+)", b) or [None, 0])[1]),
        "fieldPsynergy": "fieldPsynergy" in b,
    })

# the classes that teach it
classes = defaultdict(list)
ctable = read("src/game/class_table.c")
blocks = re.split(r"\n    // ([^\n]*)\n    \{", ctable)
for i in range(1, len(blocks), 2):
    cname, cbody = blocks[i], blocks[i + 1]
    for ab, lv in re.findall(r"\.ability = (\d+), \.level = (\d+)", cbody):
        classes[int(ab)].append((int(lv), cname))

# the items that grant it
ids = {m.group(1): int(m.group(2), 0) for m in re.finditer(r"ABILITY_(\w+) = (0x[0-9a-fA-F]+|\d+)", read("include/ability_ids.h"))}
items = defaultdict(list)
itable = read("src/game/item_table.c")
iblocks = re.split(r"\n    // ([^\n]*)\n    \{", itable)
for i in range(1, len(iblocks), 2):
    m = re.search(r"\.useType = ITEM_USE_TEACHES.*?\.abilityId = ABILITY_(\w+)", iblocks[i + 1], re.S)
    if m and m.group(1) in ids:
        items[ids[m.group(1)]].append(iblocks[i])

# the arena shop
shop = {}
shopsrc = read("src/shop/shop/arena_shop.c")
sect = shopsrc[shopsrc.index("sArenaShopPsynergy[] = {"):]
sect = sect[:sect.index("};")]
for a, p in re.findall(r"\{(\d+), (\d+)\}", sect):
    shop[int(a)] = int(p)

learnable = set(classes) | set(items) | set(shop)
DJINNI = range(0x12c, 0x12c + 28)


def row(n):
    a = abilities[n]
    use = ("battle" if a["battle"] else "") + (" + field" if a["battle"] and a["field"] else "field" if a["field"] else "")
    src = []
    if n in classes:
        src.append("%d classes, from level %d" % (len(classes[n]), min(l for l, _ in classes[n])))
    if n in items:
        src.append("item: " + ", ".join(items[n]))
    if n in shop:
        src.append("arena shop")
    return "| %d | %s | %s | %d | %s | %s | %s |" % (
        n, by_number.get(n, "?"), a["element"].title(), a["pp"], use or "-",
        a["kind"].lower().replace("_", " "), "; ".join(src) or "none")


HEADER = "| id | name | element | PP | usable | kind | taught by |\n|---|---|---|---|---|---|---|"
print("# Psynergy: where each ability comes from\n")
print("Generated by `scripts/psynergy-sources.py` from the decompilation's tables; do not edit.\n")
print("The table has %d abilities: %d taught by a class, %d granted by an item, %d sold by the "
      "arena shop (%d of those also taught by a class).\n"
      % (len(abilities), len(classes), len(items), len(shop), len(set(shop) & set(classes))))
print("## Learnable Psynergy (class, item or shop), by id\n")
print(HEADER)
for n in sorted(learnable):
    print(row(n))

print("\n## Field Psynergy that nothing teaches (the story does)\n")
print(HEADER)
for n, a in enumerate(abilities):
    if a["fieldPsynergy"] and n not in learnable:
        print(row(n))

print("\n## Battle abilities with a PP cost that no class, item or shop teaches\n")
print("Djinn and summons are left out. A kind of `enemy damage` is an enemy's own move; "
      "the rest are candidates to teach to a class.\n")
print(HEADER)
for n, a in enumerate(abilities):
    if (n in learnable or n in DJINNI or a["kind"] == "SUMMON" or not a["battle"]
            or a["pp"] == 0 or n in (0, 1, 2)):
        continue
    print(row(n))
