"""Generates the cup files in ~/alchemy/games/tbs from scripts/cupdata.py.

Run in WSL:  python3 scripts/gen-cups.py
Writes (all marked generated; edit cupdata.py, not these):
  include/module/arena_cups.h          counts, structs, externs
  src/battle/arena_cups.c              the teams of every cup (its own object: objects.tsv row)
  src/scene/arena_cup_info.inc         per-cup info, rewards, shop rows (arena_menu.c includes it)
  src/shop/shop/arena_djinn_gate.inc   when the manager sells each Djinni (arena_shop.c)
  text/en.po                           the block between the BEGIN and END GENERATED CUPS
                                       comments (messages for the cups), always last in the file
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cupdata as D
import cupgame as G

BEGIN = "# BEGIN GENERATED CUPS (scripts/gen-cups.py; do not edit by hand)"
END = "# END GENERATED CUPS"
FLAG_REWARD_FIRST = 0x7A0
REWARD_FLAG_MAX = 64
HEADER = "/* Generated by scripts/gen-cups.py from scripts/cupdata.py. Do not edit. */\n"


def wrap(text, width=20):
    """Hand-broken lines of at most `width` characters."""
    lines, cur = [], ""
    for w in text.split(" "):
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + " " + w) if cur else w
    if cur:
        lines.append(cur)
    return lines


def pages(parts):
    """Joins page texts with {page_break}, at most four lines a page."""
    out = []
    for p in parts:
        lines = p if isinstance(p, list) else wrap(p)
        while len(lines) > 4:
            out.append(lines[:4])
            lines = lines[4:]
        out.append(lines)
    return "{page_break}".join("\\n".join(l) for l in out)


def po(ctx, msgid, text):
    """One message; text uses \\n for line breaks (already escaped)."""
    parts = text.split("\\n")
    body = "".join('"%s%s"\n' % (p, "\\n" if i < len(parts) - 1 else "") for i, p in enumerate(parts))
    return 'msgctxt "%s"\nmsgid "%d"\nmsgstr ""\n%s\n' % (ctx, msgid, body)


def join_names(names):
    if len(names) == 1:
        return names[0]
    return ", ".join(names[:-1]) + " and " + names[-1]


def main():
    game = G.GAME
    cups = D.CUPS
    n = len(cups)
    main_n = D.MAIN_COUNT

    # ------------------------------------------------------------- messages
    po_path = os.path.join(game, "text/en.po")
    text = open(po_path, encoding="utf-8").read()
    if BEGIN in text:
        text = text[:text.index(BEGIN)].rstrip("\n") + "\n"
    ids = [int(m) for m in re.findall(r'^msgid "(\d+)"', text, re.M)]
    assert ids == list(range(len(ids))), "message ids are not contiguous"
    next_id = len(ids)
    blocks = []
    msg = {}

    def add(ctx, body):
        nonlocal next_id
        blocks.append(po(ctx, next_id, body))
        msg[ctx] = next_id
        next_id += 1
        return next_id - 1

    # the names first: the cup rows take their labels as consecutive messages
    for i, c in enumerate(cups):
        add("MsgArenaCupName%d" % i, c.name)
    add("MsgArenaCupNext", "Next cup")
    add("MsgArenaCupReplay", "Replay")
    add("MsgArenaCupSide", "Side cups")
    add("MsgArenaCupReplayPrompt", "Replay which cup?{end_now}")
    add("MsgArenaCupGroupEarly", "Early cups")
    add("MsgArenaCupGroupLate", "Later cups")
    add("MsgArenaCupSidePrompt", "Which side cup\\nwill you enter?{end_now}")
    add("MsgArenaGearReward", "A find from the\\ndungeon! It is yours.{end_wait}")
    add("MsgArenaDjinnNoRoom", "Your Djinn are full!\\nMake room, then win\\nthis round again.{end_wait}")
    reward_flag = 0
    info = {}
    for i, c in enumerate(cups):
        e = {}
        e["confirm"] = add("MsgArenaCupConfirm%d" % i,
                           "Enter the\\n%s?{end_now}" % c.name)
        e["cleared"] = add("MsgArenaCupCleared%d" % i,
                           "You cleared the\\n%s!\\nCongratulations!{end_wait}" % c.name)
        # the first-clear scene
        parts = [["Well done!", "You cleared the", "%s!" % c.name]]
        if c.raise_to:
            parts.append("Your party grows stronger. All of you rise to level %d!" % c.raise_to)
        if c.sells:
            parts.append("Djinn for sale at the party manager: %s." % join_names(c.sells))
        if c.shops:
            parts.append("New goods at the shops of %s." % c.shops)
        if not c.side and i + 1 < main_n:
            parts.append("The %s is now open!" % cups[i + 1].name)
        elif i == main_n - 1:
            parts.append("The Boss Rush and Crossbone Isle are now open!")
        e["first"] = add("MsgArenaCupFirst%d" % i, pages(parts) + "{end_wait}")
        e["rewards"] = []
        for ri, rd in enumerate(c.rounds):
            for rw in rd.rewards:
                if reward_flag >= REWARD_FLAG_MAX:
                    raise SystemExit("too many rewards for the flag block")
                if rw[0] == "djinn":
                    nm = rw[1]
                    m = add("MsgArenaCup%dDjinn%s" % (i, nm),
                            "You won the Djinni\\n%s!\\nIt joins your party.{end_wait}" % nm)
                    e["rewards"].append((ri + 1, 1, reward_flag, D.djinn_entry(nm), 0, m))
                else:
                    e["rewards"].append((ri + 1, 0, reward_flag, 0, G.item_ids()[rw[1]], 0))
                reward_flag += 1
        info[i] = e
    marker_block = BEGIN + "\n\n" + "\n".join(blocks) + END + "\n"
    open(po_path, "w", encoding="utf-8", newline="\n").write(text.rstrip("\n") + "\n\n" + marker_block)

    # ----------------------------------------------------------- arena_cups.h
    h = [HEADER, "#ifndef ALCHEMY_MODULE_ARENA_CUPS_H\n#define ALCHEMY_MODULE_ARENA_CUPS_H\n\n",
         '#include "types.h"\n\n',
         "#define ARENA_CUP_COUNT %d\n" % n,
         "#define ARENA_MAIN_CUPS %d\n" % main_n,
         "#define ARENA_REWARD_FLAG_FIRST 0x%X\n" % FLAG_REWARD_FIRST]
    for i, cup in enumerate(cups):
        h.append("#define ARENA_CUP_%s %d\n" % (cup.short.upper().replace(" ", "_"), i))
    h += [
         "#define ARENA_CUP_SIDE 0x01  /* beside the line: not counted in progress */\n",
         "#define ARENA_CUP_HEALS 0x02 /* the party is healed after each win */\n",
         "#define ARENA_REWARD_ITEM 0\n#define ARENA_REWARD_DJINN 1\n\n",
         '#include "battle/formations.h"\n\n',
         "/// One round: win number n of a cup fights round n; its enemies are levelled to targetLevel.\n",
         "struct ArenaTeam {\n  u8 targetLevel;\n  struct Formation formation;\n};\n\n",
         "struct ArenaCupTeams {\n  const struct ArenaTeam *rounds;\n  s32 count;\n};\n",
         "extern const struct ArenaCupTeams gArenaCupTeams[];\n\n",
         "/// Given the first time round `afterRound` (1-based) is won. `flag` is the\n",
         "/// bit that says it was given; `value` the Djinni (element * 7 + n); `item`\n",
         "/// the item id; `message` the message said for a Djinni.\n",
         "struct ArenaCupReward {\n  u8 afterRound;\n  u8 kind;\n  u8 flag;\n  u8 value;\n  u16 item;\n  u16 message;\n};\n\n",
         "struct ArenaCupInfo {\n  u8 roundCount;\n  u8 flags;\n  u8 requires; /* main cups cleared before it opens */\n  u8 raiseTo;   /* party level at the first clear, 0 for none */\n",
         "  u8 rewardCount;\n  u8 pad[3];\n  const struct ArenaCupReward *rewards;\n  u16 confirmMsg;\n  u16 clearedMsg;\n  u16 firstMsg;\n  u16 pad2;\n};\n\n",
         "extern const struct ArenaCupInfo gArenaCupInfo[ARENA_CUP_COUNT];\n",
         "/// Item shop rows (weapons, armor, supplies) by cups cleared, 0 to ARENA_MAIN_CUPS.\n",
         "extern const u8 gArenaShopRows[ARENA_MAIN_CUPS + 1][3];\n",
         "extern const u8 gArenaCrossboneRows[3];\n\n",
         "#define MSG_ARENA_CUP_NAME %d\n" % msg["MsgArenaCupName0"], "\n#endif\n"]
    open(os.path.join(game, "include/module/arena_cups.h"), "w", newline="\n").write("".join(h))

    # ------------------------------------------------------------ arena_cups.c
    c = [HEADER, "// The teams of every cup; arena_ladder.c (part of battle.c) picks the round.\n\n",
         '#include "module/arena.h"\n\n',
         "// clang-format off\n"]
    for i, cup in enumerate(cups):
        c.append("// %d: %s\nstatic const struct ArenaTeam gArenaCup%dRounds[%d] = {\n" % (i, cup.name, i, len(cup.rounds)))
        for rd in cup.rounds:
            ids = ", ".join(str(a) for a, _ in rd.team)
            cnt = ", ".join(str(b) for _, b in rd.team)
            c.append("    // %s\n    {%d, {.layout = 2, .memberIds = {%s}, .minimumCounts = {%s}, .maximumCounts = {%s}}},\n"
                     % (rd.note, rd.level, ids, cnt, cnt))
        c.append("};\n\n")
    c.append("const struct ArenaCupTeams gArenaCupTeams[ARENA_CUP_COUNT] = {\n")
    for i, cup in enumerate(cups):
        c.append("    {gArenaCup%dRounds, %d},\n" % (i, len(cup.rounds)))
    c.append("};\n// clang-format on\n")
    open(os.path.join(game, "src/battle/arena_cups.c"), "w", newline="\n").write("".join(c))

    # --------------------------------------------------------- arena_cup_info.inc
    s = [HEADER, "// Included by arena_menu.c. Global const data: a scene overlay has no static data of its own.\n\n"]
    for i, cup in enumerate(cups):
        e = info[i]
        if e["rewards"]:
            s.append("const struct ArenaCupReward gArenaCup%dRewards[] = {\n" % i)
            for r in e["rewards"]:
                s.append("    {%d, %d, %d, %d, %d, %d},\n" % r)
            s.append("};\n")
    s.append("\nconst struct ArenaCupInfo gArenaCupInfo[ARENA_CUP_COUNT] = {\n")
    for i, cup in enumerate(cups):
        e = info[i]
        flags = (1 if cup.side else 0) | (2 if cup.heals else 0)
        s.append("    // %s\n    {%d, %d, %d, %d, %d, {0}, %s, %d, %d, %d, 0},\n" % (
            cup.name, len(cup.rounds), flags, cup.requires, cup.raise_to, len(e["rewards"]),
            "gArenaCup%dRewards" % i if e["rewards"] else "0", e["confirm"], e["cleared"], e["first"]))
    s.append("};\n\nconst u8 gArenaShopRows[ARENA_MAIN_CUPS + 1][3] = {\n")
    for r in D.SHOP_ROWS:
        s.append("    {%d, %d, %d},\n" % r)
    s.append("};\nconst u8 gArenaCrossboneRows[3] = {%d, %d, %d};\n" % D.CROSSBONE_ROWS)
    open(os.path.join(game, "src/scene/arena_cup_info.inc"), "w", newline="\n").write("".join(s))

    # ------------------------------------------------------ arena_djinn_gate.inc
    gate = [255] * 28
    for nm in D.START_SELLS:
        gate[D.djinn_entry(nm)] = 0
    for i, cup in enumerate(cups):
        for nm in cup.sells:
            gate[D.djinn_entry(nm)] = (i + 1) if not cup.side else (0x80 | (i - main_n))
    g = [HEADER, "// Included by arena_shop.c. When the party manager sells each Djinni (entry = element * 7 + n):\n",
         "// 0 from the start, 1 to %d once that many cups are cleared, 0x80 + n once side cup n is cleared, 255 never.\n" % main_n,
         "static const u8 sArenaDjinnGate[28] = {\n"]
    for e in range(4):
        g.append("    " + ", ".join(str(gate[e * 7 + k]) for k in range(7)) + ", // " + D.ELEMENTS[e] + "\n")
    g.append("};\n")
    open(os.path.join(game, "src/shop/shop/arena_djinn_gate.inc"), "w", newline="\n").write("".join(g))
    print("generated: %d cups, %d messages (ids %d to %d), %d reward flags" % (
        n, len(blocks), msg["MsgArenaCupName0"], next_id - 1, reward_flag))


if __name__ == "__main__":
    main()
